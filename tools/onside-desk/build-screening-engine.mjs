// Development-only: keep the offline Mac reviewer aligned with the service's rules.
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
const sources=['src/lib/profanity/lyrics.ts','config/profanity_lyrics.json','src/lib/foreign-lyrics.ts','src/lib/lyrics-translation-validation.ts'];
const digest=createHash('sha256');
for(const source of sources) digest.update(source).update(await readFile(path.join(root,source)));
const version=digest.digest('hex');
await build({
  stdin:{contents:`export { analyzeLyricsProfanity, LYRICS_PROFANITY_LIMITS } from './src/lib/profanity/lyrics.ts';\nexport { findForeignLyricsSpans, inlineLyricTranslation } from './src/lib/foreign-lyrics.ts';\nexport { isUsableLyricsTranslation } from './src/lib/lyrics-translation-validation.ts';\nexport const SCREENING_ENGINE_VERSION = '${version}';`,resolveDir:root,sourcefile:'offline-screening-entry.mjs'},
  outfile:path.join(here,'screening-engine.mjs'),bundle:true,format:'esm',platform:'node',target:'node22',legalComments:'none',
  banner:{js:'// Generated by build-screening-engine.mjs. Service rules bundled locally; no network calls.'},
});
console.log(`Offline screening rules: ${version.slice(0,12)}`);
